@NoArgsConstructor
public class EmailVerificationRequest {

    @NotBlank(message = "이메일은 필수 입력값입니다.")
    @Email(message = "이메일 형식이 올바르지 않습니다.")
    private String email;

    // 인증 코드 확인시 사용
    private String code;

}
